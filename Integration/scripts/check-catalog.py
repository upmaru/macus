#!/usr/bin/env python3
"""Validate the reviewable image pins and synchronize the embedded Swift entry."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "Integration" / "catalog"
SWIFT = ROOT / "Sources" / "Macus" / "Bootstrap" / "ApplianceCatalog.swift"
PAYLOAD = ROOT / "Sources" / "Macus" / "Bootstrap" / "EmbeddedGuestPayload.swift"
RELEASE = "https://github.com/upmaru/macus-appliance"
MARKER = "  // Generated by Integration/scripts/check-catalog.py --write.\n"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def valid_digest(value, length):
    return (isinstance(value, str) and re.fullmatch(rf"[0-9a-f]{{{length}}}", value) is not None
            and len(set(value)) > 1)


def validate(entry):
    image_id = entry["id"]
    channel = entry["channel"]
    versions = {"schema_version": 2, "catalog_version": 2, "image_format": 1,
                "manifest_version": 1, "helper_version": 1}
    for field, expected in versions.items():
        require(type(entry[field]) is int and entry[field] == expected, f"Unsupported {field}")
    require(entry["architecture"] == "arm64" and entry["member_name"] == "disk.raw", "Invalid archive layout")
    require(channel in ("lts", "stable")
            and re.fullmatch(rf"alpine-\d+\.\d+\.\d+-{channel}-[1-9]\d*", image_id), "Invalid appliance ID or channel")
    archive = f"{image_id}.raw.tar.gz"
    require(entry["archive_name"] == archive
            and entry["archive_url"] == f"{RELEASE}/releases/download/{image_id}/{archive}",
            "Catalog URL must point to the matching macus-appliance release asset")
    for field, maximum in (("archive_bytes", 2**31 - 1), ("raw_bytes", 16 * 2**30)):
        require(type(entry[field]) is int and 0 < entry[field] <= maximum, f"Invalid measured {field}")
    require(re.fullmatch(r"v\d+\.\d+", entry["alpine_branch"])
            and re.fullmatch(rf"\d[0-9A-Za-z._+-]+-{channel}", entry["kernel_release"]),
            "Invalid Alpine branch or kernel release")
    for field, length in (("archive_sha512", 128), ("raw_sha256", 64), ("lock_sha256", 64),
                          ("manifest_sha256", 64), ("guest_payload_revision", 64)):
        require(valid_digest(entry[field], length), f"Invalid {field}")
    packages = entry["qualified_packages"]
    required_packages = {"incus", "zfs", "zfs-libs", "zfs-openrc", f"linux-{channel}", f"zfs-{channel}"}
    require(required_packages <= packages.keys()
            and all(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9+_.-]*", name)
                    and isinstance(version, str)
                    and re.fullmatch(r"[0-9][A-Za-z0-9._+~-]*-r\d+", version)
                    for name, version in packages.items()),
            "Qualified packages must record exact revisions")
    upstream, build = entry["upstream"], entry["build"]
    require(upstream["signer_fingerprint"] == "F26ADFADBAE702EF7AF637459DA7EF23BFFCDF22"
            and upstream["signing_key_url"] == "https://alpinelinux.org/keys/tomalok.asc"
            and re.fullmatch(r"alpine-[a-zA-Z0-9._-]+\.raw\.tar\.gz", upstream["archive_name"])
            and valid_digest(upstream["archive_sha512"], 128)
            and valid_digest(upstream["raw_sha256"], 64), "Invalid upstream provenance")
    require(valid_digest(build["commit"], 40)
            and re.fullmatch(rf"{re.escape(RELEASE)}/actions/runs/\d+", build["workflow_run_url"])
            and re.fullmatch(rf"{re.escape(RELEASE)}/attestations/\d+", build["attestation_url"]),
            "Invalid build provenance")


def load_catalog(files):
    entries = []
    channels = set()
    for file in files:
        entry = json.loads(file.read_text())
        validate(entry)
        require(entry["channel"] not in channels, "Duplicate catalog channel")
        channels.add(entry["channel"])
        entries.append(entry)
    # The CLI still selects a single default. Adding another shipped channel
    # requires the channel-selection and persistence change.
    require(channels == {"lts"}, "The current startup path requires one shipped LTS entry")
    return entries[0]


def render(entry):
    upstream, build = entry["upstream"], entry["build"]
    packages = "".join(f'      "{name}": "{version}",\n'
                       for name, version in sorted(entry["qualified_packages"].items()))
    return f'''  static let current = ApplianceCatalogEntry(
    schemaVersion: {entry["schema_version"]},
    id: "{entry["id"]}",
    architecture: "{entry["architecture"]}",
    archiveName: "{entry["archive_name"]}",
    archiveURL: URL(
      string:
        "{entry["archive_url"]}"
    )!,
    archiveSHA512:
      "{entry["archive_sha512"]}",
    archiveBytes: {entry["archive_bytes"]:_},
    memberName: "{entry["member_name"]}",
    rawBytes: {entry["raw_bytes"]:_},
    rawSHA256: "{entry["raw_sha256"]}",
    upstream: Upstream(
      archiveName: "{upstream["archive_name"]}",
      archiveSHA512:
        "{upstream["archive_sha512"]}",
      rawSHA256: "{upstream["raw_sha256"]}",
      signerFingerprint: "{upstream["signer_fingerprint"]}",
      signingKeyURL: URL(string: "{upstream["signing_key_url"]}")!),
    build: Build(
      commit: "{build["commit"]}",
      workflowRunURL: URL(
        string: "{build["workflow_run_url"]}")!,
      attestationURL: URL(
        string: "{build["attestation_url"]}")!),
    catalogVersion: {entry["catalog_version"]},
    manifestVersion: {entry["manifest_version"]},
    helperVersion: {entry["helper_version"]},
    qualifiedPackages: [
{packages}    ],
    guestPayloadRevision: EmbeddedGuestPayload.revision,
    prebuiltIdentity: PrebuiltImageIdentity(
      imageFormat: {entry["image_format"]},
      channel: "{entry["channel"]}",
      alpineBranch: "{entry["alpine_branch"]}",
      lockSHA256: "{entry["lock_sha256"]}",
      manifestSHA256: "{entry["manifest_sha256"]}",
      kernelRelease: "{entry["kernel_release"]}"))
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        entry = load_catalog(sorted(CATALOG.glob("*.json")))
        revision = re.search(r'static let revision = "([0-9a-f]{64})"', PAYLOAD.read_text())
        require(revision and entry["guest_payload_revision"] == revision.group(1),
                "Catalog guest_payload_revision does not match embedded payload")
        current = SWIFT.read_text()
        prefix, marker, _ = current.partition(MARKER)
        require(marker, "Missing generated catalog marker")
        expected = prefix + marker + render(entry)
        if args.write:
            SWIFT.write_text(expected)
        else:
            require(current == expected, "Embedded catalog is out of sync. Run check-catalog.py --write")
    except (ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    print("catalog provenance matches embedded payload")


if __name__ == "__main__":
    main()
