defmodule Macus.MCP.Manifest do
  @moduledoc """
  The combined operation manifest behind `/mcp`: every operation `search`
  can find and `execute` can run, by cassette and source, with its scope,
  destructive flag and confirmation field.

  It is generated from the same documents the operation index holds: the
  locked `:opsmaru_incus` composite and native documents (the
  `opsmaru_incus` cassette) and `Macus.Dex.RuntimeDocument` (the `macus`
  cassette). `docs/mcp-operations.md` is `markdown/0`; regenerate it with
  `mix macus.mcp.manifest` after changing a document or the locked
  dependency.
  """

  alias Opsmaru.Incus.Operations.{Composite, Native}

  @type operation :: %{
          cassette: String.t(),
          source: String.t(),
          operation_id: String.t(),
          summary: String.t(),
          scopes: [String.t()],
          destructive: boolean(),
          confirmation: String.t() | nil
        }

  @doc "The indexed documents as `{cassette, document}`, in manifest order."
  @spec documents() :: [{String.t(), map()}]
  def documents,
    do: [
      {"macus", Macus.Dex.RuntimeDocument.document()},
      {"opsmaru_incus", Composite.openapi()},
      {"opsmaru_incus", Native.openapi()}
    ]

  @doc "Every operation, grouped by cassette and source and sorted by operation ID."
  @spec operations() :: [operation()]
  def operations do
    Enum.flat_map(documents(), fn {cassette, document} ->
      source = document["x-tama-source"]

      for {_path, item} <- document["paths"],
          {_method, op} <- item,
          is_map(op) and is_binary(op["operationId"]) do
        %{
          cassette: cassette,
          source: source,
          operation_id: op["operationId"],
          summary: op["summary"] || "",
          scopes: op["x-tama-scopes"] || [],
          destructive: op["x-tama-destructive"] == true,
          confirmation: get_in(op, ["x-tama-confirmation", "field"])
        }
      end
      |> Enum.sort_by(& &1.operation_id)
    end)
  end

  @doc "The manifest as Markdown, the content of `docs/mcp-operations.md`."
  @spec markdown() :: String.t()
  def markdown do
    operations = operations()
    groups = Enum.chunk_by(operations, &{&1.cassette, &1.source})

    versions =
      Map.new(documents(), fn {_, doc} -> {doc["x-tama-source"], doc["info"]["version"]} end)

    [
      """
      # MCP operation manifest

      <!-- Generated by `mix macus.mcp.manifest` from the indexed documents. Do not edit. -->

      Every operation the `/mcp` `search` and `execute` tools serve, by
      cassette and source. A caller sees only the operations its token's
      scopes allow; the `incus.native.*` scopes are granted only when a token
      is issued with them by name. Pass the confirmation field, when there is
      one, in `execute`'s `input`. See [the MCP guide](mcp.md) for how to call
      them.

      | Cassette | Source | Version | Operations |
      | --- | --- | --- | --- |
      """,
      Enum.map(groups, fn [first | _] = group ->
        "| `#{first.cassette}` | `#{first.source}` | #{versions[first.source]} | #{length(group)} |\n"
      end),
      "| | | Total | #{length(operations)} |\n",
      Enum.map(groups, &section/1)
    ]
    |> IO.iodata_to_binary()
  end

  defp section([first | _] = group) do
    scopes =
      group
      |> Enum.flat_map(& &1.scopes)
      |> Enum.frequencies()
      |> Enum.sort()
      |> Enum.map_join(", ", fn {scope, count} -> "`#{scope}` #{count}" end)

    [
      "\n## `#{first.cassette}` / `#{first.source}`\n\n",
      "#{length(group)} operations: #{scopes}.\n\n",
      "| Operation | Summary | Scope | Destructive | Confirmation |\n",
      "| --- | --- | --- | --- | --- |\n",
      Enum.map(group, &row/1)
    ]
  end

  defp row(op) do
    confirmation = if op.confirmation, do: "`#{op.confirmation}`", else: ""
    destructive = if op.destructive, do: "yes", else: ""
    scopes = Enum.map_join(op.scopes, ", ", &"`#{&1}`")

    "| `#{op.operation_id}` | #{cell(op.summary)} | #{scopes} | #{destructive} | #{confirmation} |\n"
  end

  defp cell(text),
    do: text |> String.replace(~r/\s+/, " ") |> String.replace("|", "\\|") |> String.trim()
end
